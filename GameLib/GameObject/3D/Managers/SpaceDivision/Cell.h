#pragma once

//====================================================//
// インクルードファイル
//====================================================//
#include "ObjectForTree.h"

//====================================================//
// 前方宣言
//====================================================//


//====================================================//
// クラス宣言
//====================================================//
class Cell
{
private:

    //-----------------------------------------------------
    // メンバ変数
    //-----------------------------------------------------

    ObjectForTree* m_pLatest; // 最新のオブジェクトへのポインタ

public:

    //-----------------------------------------------------
    // コンストラクタ / デストラクタ
    //-----------------------------------------------------
    Cell() 
        : m_pLatest{ nullptr }
     {
    };
    ~Cell() = default;

    //-----------------------------------------------------
    // 公開関数
    //-----------------------------------------------------

    bool AddObject(ObjectForTree* obj)
    {
        // nullをスキップ
        if (!obj) return false;

        // 登録済みをスキップ
        if (obj->m_pCell == this) return false;

        // オブジェクトが未登録なら
        if (!m_pLatest)
        {
            m_pLatest = obj;
        }
        // オブジェクトが登録済みなら
        else
        {
            // リストへ追加
            m_pLatest->m_pNext = obj;   // 最新の次を追加
            obj->m_pPre = m_pLatest;    // 追加されるポインタの前を登録
            m_pLatest = obj;            // 最新を更新
        }

        // オブジェクトを自身に所属させる
        m_pLatest->m_pCell = this;
        return true;
    }

    bool OnRemove(ObjectForTree* obj)
    {
        if (m_pLatest == obj) {
            // 前のオブジェクトに挿げ替え
            m_pLatest = m_pLatest->m_pPre;
        }
        return true;
    }

    void ResetLink(ObjectForTree* & obj)
    {
        // 次が存在するとき
        if (obj->m_pNext)
        {
            ResetLink(obj->m_pNext);
        }
        obj = nullptr;
    }

    ObjectForTree* GetFirstObject() { return m_pLatest; }

private:

    //-----------------------------------------------------
    // 内部実装
    //-----------------------------------------------------

};