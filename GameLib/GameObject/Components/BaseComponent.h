class BaseComponent
{
private:

    //-----------------------------------------------------
    // メンバ変数
    //-----------------------------------------------------

    // 自身の所有者のポインタ
    GameObject* m_own;

    // アクティブフラグ
    bool m_isActive;

public:

    //-----------------------------------------------------
    // コンストラクタ / デストラクタ
    //-----------------------------------------------------
    BaseComponent(GameObject* own);
    virtual ~BaseComponent();

    //-----------------------------------------------------
    // ゲッター
    //-----------------------------------------------------
    GameObject* GetOwn() const { return m_own; }

    bool IsActive() const { return m_isActive; }

    //-----------------------------------------------------
    // セッター
    //-----------------------------------------------------

    void SetActive(bool f) { m_isActive = f; }

private:

    //-----------------------------------------------------
    // 内部実装
    //-----------------------------------------------------

};